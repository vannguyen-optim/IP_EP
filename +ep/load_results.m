function [runs,records,manifest] = load_results(results_dir)
%LOAD_RESULTS Read only checkpoints compatible with the saved manifest.
m=load(fullfile(results_dir,'manifest.mat'),'manifest'); manifest=m.manifest;
records={}; rows=struct([]);
counter_names={'update_subproblems','diagnostic_subproblems',...
    'update_projections','diagnostic_projections',...
    'update_operator_evaluations','diagnostic_operator_evaluations',...
    'update_inner_work','diagnostic_inner_work'};
for k=1:numel(manifest.expected_keys)
    path=fullfile(results_dir,'checkpoints',[manifest.expected_keys{k},'.mat']);
    if ~isfile(path), continue; end
    s=load(path,'meta','result','signature');
    if ~isfield(s,'signature') || ~strcmp(s.signature,manifest.expected_signatures{k}), continue; end
    if ~isfield(s,'meta') || ~isfield(s,'result'), continue; end
    r=s.result; meta=s.meta;
    row=struct('model_id',string(meta.model_id),'model_name',string(meta.model_name),...
        'model_type',string(meta.model_type),'method_key',string(meta.method_key),...
        'method_name',string(meta.method_name),'matched_step',meta.matched_step,...
        'trial',meta.trial,'seed',meta.seed,'dimension',meta.n,'status',string(r.status),...
        'message',string(getvalue(r,'message','')),...
        'data_source',string(meta.data_source),'parallel',meta.parallel,...
        'iterations',getnum(r,'iterations'),'time_seconds',getnum(r,'time_seconds'),...
        'residual',getnum(r,'residual'),'reference_error',getnum(r,'reference_error'),...
        'objective',getnum(r,'objective'),'gap_upper_bound',getnum(r,'gap_upper_bound'),...
        'relative_gap',NaN,'total_subproblems',NaN,...
        'feasibility',getnum(r,'feasibility'),'energy_error_kwh',getnum(r,'energy_error_kwh'),...
        'bound_error_kw',getnum(r,'bound_error_kw'),'max_subproblem_kkt',getnum(r,'max_subproblem_kkt'),...
        'gamma',getnum(r,'gamma'),'lambda',getnum(r,'lambda'),'eta',getnum(r,'eta'),...
        'alpha',getnum(r,'alpha'),'update_subproblems',NaN,'diagnostic_subproblems',NaN,...
        'update_projections',NaN,'diagnostic_projections',NaN,...
        'update_operator_evaluations',NaN,'diagnostic_operator_evaluations',NaN,...
        'update_inner_work',NaN,'diagnostic_inner_work',NaN,'N',NaN);
    if isfield(r,'counts')
        % Keep the table schema fixed; all original counters remain in records.
        for j=1:numel(counter_names)
            name=counter_names{j};
            if isfield(r.counts,name), row.(name)=r.counts.(name); end
        end
    end
    if ~isnan(row.objective)
        row.relative_gap=row.gap_upper_bound/max(1,row.objective);
    end
    row.total_subproblems=row.update_subproblems+row.diagnostic_subproblems;
    if isfield(meta,'N'), row.N=meta.N; end
    if isempty(rows)
        rows=row;
    else
        rows(end+1)=row; %#ok<AGROW>
    end
    records{end+1}=s; %#ok<AGROW>
end
if isempty(rows), runs=table(); else, runs=struct2table(rows); end
end
function value=getnum(s,name)
value=getvalue(s,name,NaN);
end
function value=getvalue(s,name,default)
if isfield(s,name), value=s.(name); else, value=default; end
end
