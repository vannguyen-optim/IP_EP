function s = signature(p,method,cfg,seed)
%SIGNATURE Exact serialized numerical inputs prevent stale checkpoint reuse.
fingerprint='';
if isfield(cfg,'source_fingerprint'), fingerprint=cfg.source_fingerprint; end
params=struct('code_version',cfg.code_version,'model',p.signature,'seed',seed,...
    'source_fingerprint',fingerprint,'method_kind',method.kind,...
    'alpha',method.alpha,'step_ratio',method.step_ratio,...
    'eta_ratio',cfg.residual_eta_over_gamma,'tolerance',cfg.tolerance,...
    'inner_tolerance',cfg.inner_tolerance,'kkt_tolerance',cfg.kkt_tolerance,...
    'max_iter',p.max_iter,'parallel',cfg.parallel,'n_workers',cfg.n_workers,...
    'alpha_grid',cfg.alpha,'include_fast_noninertial',cfg.include_fast_noninertial,...
    'include_eg',cfg.include_eg,'include_scaled_inertial',cfg.include_scaled_inertial,...
    'scaled_alpha',cfg.scaled_alpha,...
    'matlab_version',version,'computer',computer);
s=jsonencode(params);
end
