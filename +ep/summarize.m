function summary = summarize(runs,manifest)
%SUMMARIZE Keep all recorded outcomes, including caps and numerical failures.
if isempty(runs), summary=table(); return; end
model_ids=string(manifest.model_ids);
model_ids=model_ids(~startsWith(model_ids,'ev_'));
if any(runs.model_type=="ev"), model_ids(end+1)="ev_all"; end
rows=struct([]); keys=string(manifest.expected_keys);
for p=1:numel(model_ids)
    id=model_ids(p);
    if id=="ev_all", pm=runs.model_type=="ev"; name="EV (all days)";
    else
        pm=runs.model_id==id; ix=find(pm,1);
        if isempty(ix), continue; end
        name=runs.model_name(ix);
    end
    for m=1:numel(manifest.methods)
        method=manifest.methods(m); use=pm & runs.method_key==string(method.key);
        t=runs(use,:); if isempty(t), continue; end
        qi=ep.percentile(t.iterations,[.25,.5,.75]);
        qt=ep.percentile(t.time_seconds,[.25,.5,.75]);
        if id=="ev_all"
            expected=nnz(startsWith(keys,'ev_') & endsWith(keys,['_',method.key]));
        else
            expected=nnz(startsWith(keys,[char(id),'_r']) & endsWith(keys,['_',method.key]));
        end
        row=struct('model_id',id,'model_name',name,'method_key',string(method.key),...
            'method_name',string(method.name),'matched_step',method.matched_step,...
            'n_expected',expected,'n_recorded',height(t),'n_success',nnz(t.status=="converged"),...
            'n_capped',nnz(t.status=="iteration_cap"),...
            'n_other',nnz(~ismember(t.status,["converged","iteration_cap"])),...
            'iterations_q25',qi(1),'iterations_median',qi(2),'iterations_q75',qi(3),...
            'time_q25',qt(1),'time_median',qt(2),'time_q75',qt(3),...
            'residual_median',med(t.residual),'reference_error_median',med(t.reference_error),...
            'objective_median',med(t.objective),'gap_median',med(t.gap_upper_bound),...
            'relative_gap_max',maximum(t.relative_gap),...
            'feasibility_max',maximum(t.feasibility),...
            'energy_error_kwh_max',maximum(t.energy_error_kwh),...
            'bound_error_kw_max',maximum(t.bound_error_kw),...
            'projection_count_median',med(t.update_projections+t.diagnostic_projections),...
            'total_subproblems_median',med(t.update_subproblems+t.diagnostic_subproblems),...
            'update_subproblems_median',med(t.update_subproblems),...
            'diagnostic_subproblems_median',med(t.diagnostic_subproblems),...
            'kkt_max',maximum(t.max_subproblem_kkt));
        rows(end+1)=row; %#ok<AGROW>
    end
end
if isempty(rows), summary=table(); else, summary=struct2table(rows); end
end
function y=med(x)
y=ep.percentile(x,.5);
end
function y=maximum(x)
if isempty(x) || any(isnan(x)), y=NaN; else, y=max(x); end
end
